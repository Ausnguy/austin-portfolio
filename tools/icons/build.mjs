// Writes src/data/iconPaths.js: the SVG path and brand color for each logo slug in src/data/toolIcons.js.
// Logos come from the simple-icons package. Run with `npm run icons`.
import { writeFileSync } from 'node:fs';
import * as icons from 'simple-icons';
import { iconSlugs } from '../../src/data/toolIcons.js';

const out = {};
for (const slug of iconSlugs) {
  const key = `si${slug[0].toUpperCase()}${slug.slice(1)}`;
  const icon = icons[key];
  if (!icon) throw new Error(`No simple-icons entry for "${slug}"`);
  out[slug] = { path: icon.path, hex: `#${icon.hex}` };
}
writeFileSync(
  new URL('../../src/data/iconPaths.js', import.meta.url),
  `// Generated by tools/icons/build.mjs from simple-icons (CC0). Do not edit.\nexport default ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`wrote ${Object.keys(out).length} icons`);
